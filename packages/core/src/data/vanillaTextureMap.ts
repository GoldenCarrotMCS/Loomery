export interface TextureRemapResult {
  /**
   * Bedrock-relative output path(s), e.g. "textures/blocks/log_oak.png". A few
   * Java textures fan out to several Bedrock ones — the creeper skin also feeds
   * the creeper head block, and a cat skin feeds both its Bedrock variants —
   * so this is a list rather than a single path.
   */
  outputPaths: string[];
  /** True when the path was found in a mapping table (exact match). */
  exact: boolean;
}

/**
 * Remap a Java texture path (relative to pack root, e.g.
 * "assets/minecraft/textures/block/oak_log.png") to a Bedrock pack path.
 * Returns undefined for paths that need composite handling or are unmappable.
 */
export function remapVanillaTexture(javaPath: string): TextureRemapResult | undefined {
  const match = javaPath.match(/^assets\/minecraft\/textures\/([^/]+)\/(.+)\.png$/);
  if (!match) return undefined;
  const [, category, rest] = match;
  const name = rest!;

  switch (category) {
    case "block": {
      const renamed = BLOCK_RENAMES[name];
      return { outputPaths: [`textures/blocks/${renamed ?? name}.png`], exact: renamed !== undefined };
    }
    case "item": {
      const renamed = ITEM_RENAMES[name];
      return { outputPaths: [`textures/items/${renamed ?? name}.png`], exact: renamed !== undefined };
    }
    case "models": {
      // Armor layers: Java "<material>_layer_N" → Bedrock "<material>_N",
      // with chainmail renamed to chain and turtle_scute to turtle. Overlays
      // (leather) keep their suffix: leather_layer_1_overlay → leather_1_overlay.
      const armor = name.match(/^armor\/(.+?)_layer_(\d)(_overlay)?$/);
      if (armor) {
        const material = armorMaterial(armor[1]!);
        return {
          outputPaths: [`textures/models/armor/${material}_${armor[2]}${armor[3] ?? ""}.png`],
          exact: true,
        };
      }
      break;
    }
    case "entity": {
      // 1.21.2+ equipment layout → Bedrock armor texture names. Checked first
      // because these land under `models/`, not `entity/`.
      const modern = name.match(/^equipment\/(humanoid|humanoid_leggings)\/(.+)$/);
      if (modern) {
        const material = armorMaterial(modern[2]!);
        const layer = modern[1] === "humanoid" ? "1" : "2";
        return { outputPaths: [`textures/models/armor/${material}_${layer}.png`], exact: true };
      }
      break;
    }
  }

  // Everything else: the verified path table. It wins over the per-category
  // guesses the switch above used to make, because each of its targets was
  // checked against the real Bedrock texture tree.
  const mapped = EXTRA_TEXTURE_MAP[name];
  if (mapped !== undefined) {
    const paths = Array.isArray(mapped) ? mapped : [mapped];
    return {
      outputPaths: paths.map((p) => textureOutputPath(p)),
      exact: true,
    };
  }

  // No verified mapping. Copy the texture wherever the pack already puts it,
  // which is right for the custom content packs dump under a vanilla category,
  // and flag it so the report says "approximated" rather than claiming a real
  // conversion. Animated custom block textures still reach the flipbook stage.
  switch (category) {
    case "environment":
    case "colormap":
    case "misc":
    case "map":
      return { outputPaths: [`textures/${category}/${name}.png`], exact: false };
    case "models":
      return { outputPaths: [`textures/models/${name}.png`], exact: false };
    case "entity":
      // Composites (chest, signs, beds) are corrected by a later dedicated
      // stage which overwrites these outputs.
      return { outputPaths: [`textures/entity/${name}.png`], exact: false };
    default:
      // gui, painting, particle, font, mob_effect, trims → dedicated stages
      return undefined;
  }
}

/** Prefix a table value (relative to `textures/`) with its root, adding `.tga` when Bedrock expects one. */
function textureOutputPath(relative: string): string {
  const path = `textures/${relative}`;
  if (!TGA_TEXTURE_OUTPUTS.has(relative)) return `${path}.png`;
  return `${path}.tga`;
}

/**
 * Bedrock's armor material names, which differ from Java's for two of them:
 * chainmail is `chain`, and turtle_scute is `turtle`. Getting one wrong ships
 * an armor layer Bedrock never loads, so it stays in one place.
 */
function armorMaterial(java: string): string {
  if (java === "chainmail") return "chain";
  if (java === "turtle_scute") return "turtle";
  return java;
}
